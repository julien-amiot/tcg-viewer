/**
 * Run e2e tests with Jira Test Execution tracking
 *
 * For each .feature file, creates/updates a "Test Execution" child item
 * in the corresponding Jira "Test Case" with:
 * - Current date as start date
 * - Status based on test results (Passed/Failed)
 * - Log output on failure
 * - Screenshot attachment if available
 *
 * Usage: node scripts/run-e2e-with-jira.js [--project <projectKey>]
 */

const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

// Configuration from environment variables
const JIRA_URL = process.env.JIRA_URL;
const JIRA_TOKEN = process.env.JIRA_TOKEN;
const JIRA_EMAIL = process.env.JIRA_EMAIL;

if (!JIRA_TOKEN) {
  console.error('ERROR: JIRA_TOKEN environment variable is required');
  process.exit(1);
}

if (!JIRA_URL) {
  console.error('ERROR: JIRA_URL environment variable is required');
  process.exit(1);
}

// Jira Test Case mappings (feature file -> Jira key)
// Format: JSON string of key-value pairs, e.g. '{"card-grid.feature":"TCGV-1","set-selector.feature":"TCGV-2"}'
const TEST_CASE_MAPPINGS = process.env.JIRA_TEST_CASE_MAPPINGS
  ? JSON.parse(process.env.JIRA_TEST_CASE_MAPPINGS)
  : {};

// Jira project configuration from environment variables
const JIRA_PROJECT_KEY = process.argv.includes('--project')
  ? process.argv[process.argv.indexOf('--project') + 1]
  : process.env.JIRA_PROJECT_KEY;

const JIRA_PROJECT_ID = process.env.JIRA_PROJECT_ID;

if (!JIRA_PROJECT_KEY) {
  console.error('ERROR: JIRA_PROJECT_KEY environment variable is required');
  process.exit(1);
}

if (!JIRA_PROJECT_ID) {
  console.error('ERROR: JIRA_PROJECT_ID environment variable is required');
  process.exit(1);
}

// Jira workflow statuses for Test Execution
const JIRA_STATUSES = {
  PASSED: process.env.JIRA_STATUS_PASSED || 'Passed',
  FAILED: process.env.JIRA_STATUS_FAILED || 'Failed',
  RUNNING: process.env.JIRA_STATUS_RUNNING || 'Running',
};

// Jira API helper
function jiraRequest(method, endpoint, body = null) {
  const https = require('https');
  const url = new URL(endpoint, JIRA_URL);

  return new Promise((resolve, reject) => {
    const options = {
      hostname: url.hostname,
      path: url.pathname + url.search,
      method,
      headers: {
        'Authorization': `Basic ${Buffer.from(`${JIRA_EMAIL}:${JIRA_TOKEN}`).toString('base64')}`,
        'Content-Type': 'application/json',
        'Accept': 'application/json',
      },
    };

    const req = https.request(options, (res) => {
      let data = '';
      res.on('data', (chunk) => { data += chunk; });
      res.on('end', () => {
        try {
          resolve({ status: res.statusCode, data: JSON.parse(data) });
        } catch (e) {
          resolve({ status: res.statusCode, data });
        }
      });
    });
    req.on('error', reject);
    if (body) req.write(JSON.stringify(body));
    req.end();
  });
}

function jiraPost(endpoint, body) {
  return jiraRequest('POST', endpoint, body);
}

function jiraPut(endpoint, body) {
  return jiraRequest('PUT', endpoint, body);
}

// Find existing Test Execution for a Test Case
async function findOrCreateTestExecution(testCaseKey, testName) {
  // Search for existing Test Executions linked to this Test Case
  const today = new Date().toISOString().split('T')[0];
  const jql = `issueFunction linkedIssuesOf "${testCaseKey}" AND issuetype = "Test execution" ORDER BY created DESC`;

  try {
    const searchResult = await jiraPost('/rest/api/3/search/jql', {
      jql: jql,
      maxResults: 10,
      fields: ['key', 'summary', 'status', 'created'],
    });

    // Find today's execution
    for (const issue of searchResult.data.issues) {
      const createdDate = issue.fields.created?.split('T')[0];
      if (createdDate === today) {
        console.log(`  Found existing Test Execution: ${issue.key}`);
        return issue.key;
      }
    }
  } catch (err) {
    console.log(`  Note: Could not search for existing Test Executions: ${err.message}`);
  }

  // Create new Test Execution
  console.log(`  Creating new Test Execution for ${testName}...`);
  const execResult = await jiraPost('/rest/api/3/issue', {
    fields: {
      project: { id: JIRA_PROJECT_ID },
      summary: `Test Execution: ${testName} (${today})`,
      description: [
        `## Test Execution`,
        ``,
        `**Test Case:** ${testCaseKey}`,
        `**Date:** ${today}`,
        `**Status:** Running`,
        ``,
        `### Test Details`,
        ``,
        `*Auto-generated by scripts/run-e2e-with-jira.js*`,
      ].join('\n'),
      issuetype: { name: 'Test execution' },
      parent: { key: testCaseKey },
    },
  });

  if (execResult.status === 201) {
    console.log(`  Created Test Execution: ${execResult.data.key}`);
    return execResult.data.key;
  }

  console.error(`  Failed to create Test Execution: ${JSON.stringify(execResult.data)}`);
  return null;
}

// Update Test Execution status
async function updateTestExecution(execKey, status, logOutput = '', screenshotPath = null) {
  const today = new Date().toISOString().split('T')[0];

  const description = [
    `## Test Execution`,
    ``,
    `**Date:** ${today}`,
    `**Status:** ${status}`,
    ``,
  ];

  if (status === 'Failed' && logOutput) {
    description.push('### Test Output');
    description.push('');
    description.push('```');
    description.push(logOutput);
    description.push('```');
    description.push('');
  }

  if (status === 'Passed') {
    description.push('### Result');
    description.push('');
    description.push('All scenarios passed successfully.');
  }

  description.push('');
  description.push('*Auto-generated by scripts/run-e2e-with-jira.js*');

  try {
    await jiraPut(`/rest/api/3/issue/${execKey}`, {
      fields: {
        description: description.join('\n'),
        // Note: Status transitions require workflow permissions
        // The description update ensures we capture the result
      },
    });
    console.log(`  Updated Test Execution: ${execKey} -> ${status}`);
  } catch (err) {
    console.error(`  Failed to update Test Execution: ${err.message}`);
  }

  // Attach screenshot if available
  if (status === 'Failed' && screenshotPath && fs.existsSync(screenshotPath)) {
    try {
      const attachmentData = fs.readFileSync(screenshotPath);
      const attachResult = await jiraPost(`/rest/api/3/issue/${execKey}/attachments`, {
        files: [attachmentData],
      });
      if (attachResult.status === 200) {
        console.log(`  Attached screenshot: ${screenshotPath}`);
      }
    } catch (err) {
      console.error(`  Failed to attach screenshot: ${err.message}`);
    }
  }
}

// Parse feature file to extract Jira key
function getJiraKey(featureFile) {
  const content = fs.readFileSync(featureFile, 'utf-8');
  const match = content.match(/# Jira Test Case: (TCGV-\d+)/);
  return match ? match[1] : null;
}

// Run Playwright tests
function runPlaywrightTests(featureFile) {
  const testFile = featureFile.replace('.feature', '.test.ts');
  const featureName = path.basename(featureFile, '.feature');

  console.log(`\n🧪 Running tests for: ${featureName}`);
  console.log(`   Test file: ${testFile}`);

  try {
    const output = execSync(
      `npx playwright test "${testFile}" --timeout=60000`,
      {
        encoding: 'utf-8',
        timeout: 300000, // 5 minutes max
        cwd: path.join(__dirname, '..'),
      }
    );
    return { success: true, output };
  } catch (err) {
    return { success: false, output: err.stdout || err.stderr || err.message };
  }
}

// Main
async function main() {
  console.log('='.repeat(60));
  console.log('E2E Test Runner with Jira Test Execution Tracking');
  console.log('='.repeat(60));

  const featureDir = path.join(__dirname, '..', 'test', 'e2e');
  const featureFiles = fs.readdirSync(featureDir)
    .filter(f => f.endsWith('.feature'))
    .sort();

  const results = [];

  for (const featureFile of featureFiles) {
    const jiraKey = getJiraKey(path.join(featureDir, featureFile));

    if (!jiraKey) {
      console.log(`\n⚠️  No Jira Test Case found in ${featureFile}`);
      continue;
    }

    console.log(`\n📋 Jira Test Case: ${jiraKey}`);

    // Run tests
    const featurePath = path.join(featureDir, featureFile);
    const { success, output } = runPlaywrightTests(featurePath);

    // Find screenshot on failure
    const screenshotPath = path.join(
      __dirname, '..', 'test-results',
      featureFile.replace('.feature', '').replace(/-/g, '_'),
      'test-failed-1.png'
    );

    // Update Jira
    const execKey = await findOrCreateTestExecution(jiraKey, featureFile);
    const status = success ? JIRA_STATUSES.PASSED : JIRA_STATUSES.FAILED;
    await updateTestExecution(execKey, status, output, screenshotPath);

    results.push({ feature: featureFile, jiraKey, success, output });
  }

  // Summary
  console.log('\n' + '='.repeat(60));
  console.log('Test Summary');
  console.log('='.repeat(60));

  let passed = 0;
  let failed = 0;
  for (const r of results) {
    const icon = r.success ? '✅' : '❌';
    const status = r.success ? 'PASSED' : 'FAILED';
    console.log(`  ${icon} ${r.feature} -> ${r.jiraKey} (${status})`);
    if (r.success) passed++;
    else failed++;
  }

  console.log(`\nTotal: ${results.length} | Passed: ${passed} | Failed: ${failed}`);

  if (failed > 0) {
    process.exit(1);
  }
}

main().catch((err) => {
  console.error('Fatal error:', err);
  process.exit(1);
});