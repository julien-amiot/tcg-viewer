/**
 * Create Jira Test Case tickets for each .feature file
 *
 * Usage: node scripts/create-e2e-test-cases.js
 *
 * Creates one "Task" ticket per .feature file in the configured project.
 * Each ticket is tagged with the Jira key extracted from the .feature file header.
 */

const fs = require('fs');
const path = require('path');
const axios = require('axios');

// Configuration — read from environment variables
const JIRA_URL = process.env.JIRA_URL;
const JIRA_TOKEN = process.env.JIRA_TOKEN;
const JIRA_EMAIL = process.env.JIRA_EMAIL;

if (!JIRA_URL) {
  console.error('ERROR: JIRA_URL environment variable is required');
  process.exit(1);
}

if (!JIRA_TOKEN) {
  console.error('ERROR: JIRA_TOKEN environment variable is required');
  process.exit(1);
}

const jira = axios.create({
  baseURL: JIRA_URL,
  auth: {
    username: JIRA_EMAIL,
    password: JIRA_TOKEN,
  },
  headers: {
    Accept: 'application/json',
    'Content-Type': 'application/json',
    'X-Atlassian-Token': 'no-check',
  },
});

// Jira project configuration
const JIRA_PROJECT_ID = process.env.JIRA_PROJECT_ID || '10000'; // BP (Big Picture)
const JIRA_PROJECT_KEY = process.env.JIRA_PROJECT_KEY || 'BP';
const JIRA_ISSUE_TYPE = process.env.JIRA_ISSUE_TYPE || 'Task';

// Feature file configurations
const FEATURE_FILES = [
  {
    name: 'card-grid.feature',
    testFile: 'test/e2e/card-grid.test.ts',
    title: 'Card Grid Display',
    scenarios: [
      'Cards are displayed in a grid',
      'Filter by name (A, Z)',
      'Filter by color (W, U, B, R, G)',
      'Filter by type (C, L, I, A)',
      'Filter by rarity (C, U, R, M)',
    ],
  },
  {
    name: 'set-selector.feature',
    testFile: 'test/e2e/set-selector.test.ts',
    title: 'Set Selector',
    scenarios: [
      'Set selector displays available sets',
      'Switching to a valid set updates the view',
    ],
  },
  {
    name: 'custom-card-sets.feature',
    testFile: 'test/e2e/custom-card-sets.test.ts',
    title: 'Custom Card Set Management',
    scenarios: [
      'Upload a JSON file and display cards',
      'Save a custom set with a given name',
      'Load a saved set from the dropdown',
      'Switch between saved sets',
      'Clear all filters resets the view to full set',
    ],
  },
];

async function createIssue(feature) {
  const description = [
    `## Test Case: ${feature.title}`,
    '',
    `**Feature File:** \`${feature.testFile.replace('test/', '')}\``,
    `**Test File:** \`${feature.testFile}\``,
    '',
    '### Scenarios',
    ...feature.scenarios.map((s, i) => `${i + 1}. ${s}`),
    '',
    '### Run Command',
    '```bash',
    `npx playwright test ${feature.testFile}`,
    '```',
    '',
    '### Expected Result',
    'All scenarios pass successfully.',
    '',
    '*Auto-generated by scripts/create-e2e-test-cases.js*',
  ].join('\n');

  try {
    const response = await jira.post('/rest/api/3/issue', {
      fields: {
        project: { id: JIRA_PROJECT_ID },
        summary: `E2E Test Case: ${feature.title}`,
        description,
        issuetype: { name: JIRA_ISSUE_TYPE },
        labels: ['e2e', 'playwright', 'test-case'],
      },
    });

    return { success: true, key: response.data.key };
  } catch (error) {
    const msg = error.response?.data?.errorMessages
      ? Array.isArray(error.response.data.errorMessages)
        ? error.response.data.errorMessages.join(', ')
        : error.response.data.errorMessages
      : error.message;
    return { success: false, key: null, error: `[${error.response?.status}] ${msg}` };
  }
}

async function main() {
  console.log('='.repeat(60));
  console.log('E2E Test Case Ticket Creator');
  console.log('='.repeat(60));
  console.log(`Project: ${JIRA_PROJECT_KEY} (ID: ${JIRA_PROJECT_ID})`);
  console.log(`Issue Type: ${JIRA_ISSUE_TYPE}`);
  console.log('='.repeat(60));

  let successCount = 0;
  let errorCount = 0;

  for (const feature of FEATURE_FILES) {
    console.log(`\nCreating ticket for: ${feature.title}`);
    const result = await createIssue(feature);

    if (result.success) {
      console.log(`  ✅ Created: ${result.key}`);
      successCount++;
    } else {
      console.log(`  ❌ Failed: ${result.error}`);
      errorCount++;
    }

    // Small delay to avoid rate limiting
    await new Promise((r) => setTimeout(r, 500));
  }

  console.log('\n' + '='.repeat(60));
  console.log(`Done: ${successCount} created, ${errorCount} failed`);
  console.log('='.repeat(60));

  if (errorCount > 0) {
    process.exit(1);
  }
}

main().catch((err) => {
  console.error('Fatal error:', err);
  process.exit(1);
});