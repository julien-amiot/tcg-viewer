const fs = require('fs');
const path = require('path');
const https = require('https');

// Jira credentials from environment variables
const JIRA_URL = process.env.JIRA_URL || 'https://cairnworks.atlassian.net';
const JIRA_TOKEN = process.env.JIRA_TOKEN;
const JIRA_PROJECT_ID = process.env.JIRA_PROJECT_ID || '10047';
const JIRA_ISSUE_TYPE = process.env.JIRA_ISSUE_TYPE || 'Task';

if (!JIRA_URL || !JIRA_TOKEN) {
  console.error('ERROR: JIRA_URL or JIRA_TOKEN not set');
  process.exit(1);
}

// Read test files
const cardGridTest = fs.readFileSync(path.join(__dirname, '..', 'test', 'e2e', 'card-grid.test.ts'), 'utf-8');
const setSelectorTest = fs.readFileSync(path.join(__dirname, '..', 'test', 'e2e', 'set-selector.test.ts'), 'utf-8');
const customCardSetsTest = fs.readFileSync(path.join(__dirname, '..', 'test', 'e2e', 'custom-card-sets.test.ts'), 'utf-8');

// Extract test names from test files
function extractTests(content, file) {
  const tests = [];
  // Match test('name') or test("name") where name can contain nested quotes
  const regex = /test\(['"]((?:[^'"]|'(?!")|"(?!'))*?)['"]/g;
  let match;
  while ((match = regex.exec(content)) !== null) {
    tests.push(match[1]);
  }
  return tests;
}

const testFiles = [
  { file: 'test/e2e/card-grid.test.ts', tests: extractTests(cardGridTest, 'card-grid.test.ts') },
  { file: 'test/e2e/set-selector.test.ts', tests: extractTests(setSelectorTest, 'set-selector.test.ts') },
  { file: 'test/e2e/custom-card-sets.test.ts', tests: extractTests(customCardSetsTest, 'custom-card-sets.test.ts') },
];

function createJiraIssue(testName, testFile, index) {
  const key = `TCGV-${index}`;
  const title = `[E2E] ${testName}`;
  const description = [
    `## Test Case`,
    ``,
    `**File:** ${testFile}`,
    `**Name:** ${testName}`,
    ``,
    `### Steps`,
    `1. Run Playwright E2E test: \`npx playwright test ${testFile} --grep="${testName}"\``,
    ``,
    `### Expected Result`,
    `Test passes successfully.`,
    ``,
    `### Status`,
    `- [ ] Test written`,
    `- [ ] Test passes`,
    `- [ ] Test documented`,
    ``,
    `*Auto-generated by scripts/create-e2e-issues.js*`,
  ].join('\n');

  const payload = {
    fields: {
      project: { id: JIRA_PROJECT_ID },
      summary: title,
      description,
      issuetype: { name: JIRA_ISSUE_TYPE },
      labels: ['e2e', 'playwright'],
    },
  };

  const postData = JSON.stringify(payload);
  const options = {
    hostname: JIRA_URL.replace('https://', ''),
    path: `/rest/api/3/issue`,
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'Content-Length': Buffer.byteLength(postData),
      'Authorization': `Basic ${Buffer.from(`:${JIRA_TOKEN}`).toString('base64')}`,
      'X-Atlassian-Token': 'no-check',
    },
  };

  return new Promise((resolve, reject) => {
    const req = https.request(options, (res) => {
      let data = '';
      res.on('data', (chunk) => { data += chunk; });
      res.on('end', () => {
        try {
          const result = JSON.parse(data);
          if (res.statusCode === 201) {
            resolve(result);
          } else {
            reject(new Error(`HTTP ${res.statusCode}: ${data}`));
          }
        } catch (e) {
          reject(e);
        }
      });
    });
    req.on('error', reject);
    req.write(postData);
    req.end();
  });
}

async function main() {
  let issueIndex = 1;
  let successCount = 0;
  let errorCount = 0;

  for (const tf of testFiles) {
    console.log(`\n📁 ${tf.file} (${tf.tests.length} tests)`);
    for (let i = 0; i < tf.tests.length; i++) {
      const testName = tf.tests[i];
      try {
        const result = await createJiraIssue(testName, tf.file, issueIndex);
        console.log(`  ✅ #${issueIndex}: ${result.key} - ${testName}`);
        issueIndex++;
        successCount++;
      } catch (err) {
        console.error(`  ❌ #${issueIndex}: ${testName} - ${err.message}`);
        errorCount++;
        issueIndex++;
      }
      // Small delay to avoid rate limiting
      await new Promise(r => setTimeout(r, 500));
    }
  }

  console.log(`\n✅ Done: ${successCount} created, ${errorCount} failed`);
}

main().catch(console.error);